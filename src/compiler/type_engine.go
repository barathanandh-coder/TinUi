package compiler

import (
	"fmt"
	"regexp"
	"strings"
)

// TypeKind defines the base enumeration of all known semantic types.
type TypeKind string

const (
	TypeString     TypeKind = "String"
	TypeInt        TypeKind = "Int"
	TypeFloat      TypeKind = "Float"
	TypeBool       TypeKind = "Bool"
	TypeNull       TypeKind = "Null"
	TypeUnknown    TypeKind = "Unknown"
	TypeAny        TypeKind = "Any"
	TypeComponent  TypeKind = "Component"
	TypeCollection TypeKind = "Collection"
	TypeConflict   TypeKind = "TypeConflict"
)

// ConfidenceLevel quantifies the provenance of the inference.
type ConfidenceLevel int

const (
	ConfidenceUnknown  ConfidenceLevel = 1
	ConfidenceInferred ConfidenceLevel = 2
	ConfidenceLiteral  ConfidenceLevel = 3
	ConfidenceExplicit ConfidenceLevel = 4
)

// TinType represents the resolved identity of a type.
type TinType struct {
	Kind        TypeKind
	ComponentID string   // Populated only if Kind == TypeComponent
	ElementType *TinType // Populated only if Kind == TypeCollection
}

// TypeDiagnostic stores a non-fatal warning generated by the Type Engine.
type TypeDiagnostic struct {
	Range   Range
	Message string
}

// TypeResult is the struct returned by all inference operations.
type TypeResult struct {
	Type       TinType
	Confidence ConfidenceLevel
	SourceID   string
	Diagnostic *TypeDiagnostic
}

var (
	rxInt   = regexp.MustCompile(`^-?\d+$`)
	rxFloat = regexp.MustCompile(`^-?\d+\.\d+$`)
	rxBool  = regexp.MustCompile(`^(true|false)$`)
	rxNull  = regexp.MustCompile(`^null$`)
)

// InferLiteral purely evaluates raw strings against regexes to determine the base type.
func InferLiteral(value string, sourceRange Range) TypeResult {
	value = strings.TrimSpace(value)
	
	// Dynamic value {expr} resolves to Any
	if strings.HasPrefix(value, "{") && strings.HasSuffix(value, "}") {
		return TypeResult{
			Type:       TinType{Kind: TypeAny},
			Confidence: ConfidenceInferred,
			Diagnostic: nil,
		}
	}
	
	if (strings.HasPrefix(value, `"`) && strings.HasSuffix(value, `"`)) || 
	   (strings.HasPrefix(value, `'`) && strings.HasSuffix(value, `'`)) {
		return TypeResult{
			Type:       TinType{Kind: TypeString},
			Confidence: ConfidenceLiteral,
			Diagnostic: nil,
		}
	}
	
	if rxInt.MatchString(value) {
		return TypeResult{
			Type:       TinType{Kind: TypeInt},
			Confidence: ConfidenceLiteral,
			Diagnostic: nil,
		}
	}
	
	if rxFloat.MatchString(value) {
		return TypeResult{
			Type:       TinType{Kind: TypeFloat},
			Confidence: ConfidenceLiteral,
			Diagnostic: nil,
		}
	}
	
	if rxBool.MatchString(value) {
		return TypeResult{
			Type:       TinType{Kind: TypeBool},
			Confidence: ConfidenceLiteral,
			Diagnostic: nil,
		}
	}
	
	if rxNull.MatchString(value) {
		return TypeResult{
			Type:       TinType{Kind: TypeNull},
			Confidence: ConfidenceLiteral,
			Diagnostic: nil,
		}
	}

	return TypeResult{
		Type:       TinType{Kind: TypeUnknown},
		Confidence: ConfidenceUnknown,
		Diagnostic: nil,
	}
}

// InferStateInitialization infers the type of a state based on its initial value declaration.
func InferStateInitialization(state *StateDecl) TypeResult {
	if state == nil {
		return TypeResult{Type: TinType{Kind: TypeUnknown}, Confidence: ConfidenceUnknown}
	}
	
	// A state's initial value behaves as a literal in standard TinPyUI definition
	return InferLiteral(state.Initial, state.Range)
}

// CheckAssignmentCompatibility verifies if toType can receive fromType, following widening rules.
func CheckAssignmentCompatibility(toType TinType, fromType TinType) bool {
	if toType.Kind == TypeAny || fromType.Kind == TypeAny {
		return true
	}
	if toType.Kind == TypeUnknown || fromType.Kind == TypeUnknown {
		return true
	}
	
	if toType.Kind == fromType.Kind {
		if toType.Kind == TypeComponent && toType.ComponentID != fromType.ComponentID {
			return false
		}
		if toType.Kind == TypeCollection && toType.ElementType != nil && fromType.ElementType != nil {
			return CheckAssignmentCompatibility(*toType.ElementType, *fromType.ElementType)
		}
		return true
	}
	
	// Widening Rules
	if toType.Kind == TypeFloat && fromType.Kind == TypeInt {
		return true // Int can safely widen to Float
	}
	
	// Null assignment (Nullable by default unless specifically constrained later)
	if fromType.Kind == TypeNull {
		return true
	}
	
	return false
}

func readableType(kind TypeKind) string {
	if strings.HasPrefix(string(kind), "Type") {
		return string(kind)[4:]
	}
	return string(kind)
}

func opName(op string) string {
	switch op {
	case "+":
		return "add"
	case "-":
		return "subtract"
	case "*":
		return "multiply"
	case "/":
		return "divide"
	default:
		return "operate on"
	}
}

// InferAssignment evaluates a mutation/reassignment against an established state type.
func InferAssignment(originalType TypeResult, newValue string, newRange Range) TypeResult {
	newLiteralType := InferLiteral(newValue, newRange)
	
	if !CheckAssignmentCompatibility(originalType.Type, newLiteralType.Type) {
		return TypeResult{
			Type:       TinType{Kind: TypeConflict},
			Confidence: originalType.Confidence, // Preserves the confidence of the conflict origin
			Diagnostic: &TypeDiagnostic{
				Range:   newRange,
				Message: fmt.Sprintf("TypeMismatch: Cannot assign %s to state (expected %s)", readableType(newLiteralType.Type.Kind), readableType(originalType.Type.Kind)),
			},
		}
	}
	
	// If it's a widening operation (e.g. Int -> Float), we return the wider type
	if originalType.Type.Kind == TypeInt && newLiteralType.Type.Kind == TypeFloat {
		return TypeResult{
			Type:       TinType{Kind: TypeFloat},
			Confidence: ConfidenceInferred,
			Diagnostic: nil,
		}
	}
	
	return originalType
}

// InferExpression evaluates operators and operands purely statically.
func InferExpression(left TypeResult, op string, right TypeResult, rng Range) TypeResult {
	if left.Type.Kind == TypeConflict || right.Type.Kind == TypeConflict {
		return TypeResult{Type: TinType{Kind: TypeConflict}, Confidence: ConfidenceInferred}
	}

	// Comparison operators yield Bool
	if op == ">" || op == "<" || op == ">=" || op == "<=" || op == "==" || op == "!=" {
		return TypeResult{
			Type:       TinType{Kind: TypeBool},
			Confidence: ConfidenceInferred,
		}
	}

	// Math operations
	if op == "+" || op == "-" || op == "*" || op == "/" {
		if left.Type.Kind == TypeUnknown || right.Type.Kind == TypeUnknown {
			return TypeResult{Type: TinType{Kind: TypeUnknown}, Confidence: ConfidenceUnknown}
		}

		// String concatenation overloads +
		if op == "+" {
			if left.Type.Kind == TypeString && right.Type.Kind == TypeString {
				return TypeResult{
					Type:       TinType{Kind: TypeString},
					Confidence: ConfidenceInferred,
				}
			} else if left.Type.Kind == TypeString || right.Type.Kind == TypeString {
				return TypeResult{
					Type:       TinType{Kind: TypeConflict},
					Confidence: ConfidenceInferred,
					Diagnostic: &TypeDiagnostic{
						Range:   rng,
						Message: fmt.Sprintf("TypeMismatch: Cannot add %s and %s", readableType(left.Type.Kind), readableType(right.Type.Kind)),
					},
				}
			}
		}

		if (left.Type.Kind == TypeInt || left.Type.Kind == TypeFloat) &&
		   (right.Type.Kind == TypeInt || right.Type.Kind == TypeFloat) {
			
			// Float widens the result
			if left.Type.Kind == TypeFloat || right.Type.Kind == TypeFloat {
				return TypeResult{Type: TinType{Kind: TypeFloat}, Confidence: ConfidenceInferred}
			}
			return TypeResult{Type: TinType{Kind: TypeInt}, Confidence: ConfidenceInferred}
		}
		
		return TypeResult{
			Type:       TinType{Kind: TypeConflict},
			Confidence: ConfidenceInferred,
			Diagnostic: &TypeDiagnostic{
				Range:   rng,
				Message: fmt.Sprintf("TypeMismatch: Cannot %s %s and %s", opName(op), readableType(left.Type.Kind), readableType(right.Type.Kind)),
			},
		}
	}

	return TypeResult{Type: TinType{Kind: TypeUnknown}, Confidence: ConfidenceUnknown}
}
